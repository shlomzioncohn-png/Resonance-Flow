package com.rnd.chain.service;

import com.rnd.chain.dto.Task;
import com.rnd.chain.dto.TaskDependency;
import com.rnd.chain.dto.TaskStatus;
import com.rnd.chain.event.SchedulingUpdatePublisher;
import com.rnd.chain.event.TaskSchedulingUpdatedEvent;
import com.rnd.chain.repository.InMemoryConstraintRepository;
import com.rnd.chain.repository.InMemoryTaskDependencyRepository;
import com.rnd.chain.repository.InMemoryTaskRepository;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class TaskDependencyServiceIntegrationTest {

    private UUID taskId;
    private UUID dependencyTaskId;

    private Task task;

    private InMemoryTaskRepository taskRepository;
    private InMemoryTaskDependencyRepository dependencyRepository;
    private InMemoryConstraintRepository constraintRepository;

    private RecordingSchedulingUpdatePublisher schedulingPublisher;

    private TaskDependencyService taskDependencyService;

    @BeforeEach
    void setUp() {

        taskId = UUID.randomUUID();
        dependencyTaskId = UUID.randomUUID();

        task = createTask(taskId, true);

        Task dependencyTask =
                createTask(dependencyTaskId, true);

        taskRepository =
                new InMemoryTaskRepository(
                        List.of(task, dependencyTask));

        dependencyRepository =
                new InMemoryTaskDependencyRepository(
                        List.of());

        constraintRepository =
                new InMemoryConstraintRepository(
                        List.of());

        schedulingPublisher =
                new RecordingSchedulingUpdatePublisher();

        SchedulingUpdateService schedulingUpdateService =
                new SchedulingUpdateService(
                        schedulingPublisher);

        TaskEligibilityService taskEligibilityService =
                new TaskEligibilityService(
                        taskRepository,
                        dependencyRepository,
                        constraintRepository,
                        schedulingUpdateService);

        taskDependencyService =
                new TaskDependencyService(
                        taskRepository,
                        dependencyRepository,
                        taskEligibilityService);
    }

    @Test
    void addDependency_shouldUpdateBlockingCountAndEligibility() {

        TaskDependency created =
                taskDependencyService.addDependency(
                        taskId,
                        dependencyTaskId);

        assertNotNull(created);

        // Dependency was really saved
        List<TaskDependency> dependencies =
                dependencyRepository.findByTaskId(taskId);

        assertEquals(1, dependencies.size());
        assertEquals(
                dependencyTaskId,
                dependencies.get(0).getDependsOnTaskId());

        // blockingCount was updated
        Task updatedTask =
                taskRepository.findById(taskId)
                        .orElseThrow();

        assertEquals(
                1,
                updatedTask.getBlockingCount());

        // Task became unavailable
        assertFalse(updatedTask.isReady());

        // Availability changed, therefore an event was published
        assertEquals(
                1,
                schedulingPublisher.getPublishedEvents().size());
    }

    @Test
    void removeDependency_shouldUpdateBlockingCountAndEligibility() {

        // First create the dependency
        taskDependencyService.addDependency(
                taskId,
                dependencyTaskId);

        assertEquals(
                1,
                task.getBlockingCount());

        assertFalse(task.isReady());

        // Ignore the event generated by ADD,
        // because this test focuses on REMOVE
        schedulingPublisher.clear();

        taskDependencyService.removeDependency(
                taskId,
                dependencyTaskId);

        // Dependency was really removed
        assertTrue(
                dependencyRepository
                        .findByTaskId(taskId)
                        .isEmpty());

        Task updatedTask =
                taskRepository.findById(taskId)
                        .orElseThrow();

        // blockingCount went back to zero
        assertEquals(
                0,
                updatedTask.getBlockingCount());

        // With no blockers and no open constraints,
        // the task becomes available again
        assertTrue(updatedTask.isReady());

        // Availability changed again
        assertEquals(
                1,
                schedulingPublisher.getPublishedEvents().size());
    }

    private Task createTask(
            UUID id,
            boolean ready) {

        LocalDateTime now =
                LocalDateTime.now();

        return new Task(
                id,
                null,
                TaskStatus.ACTIVE,
                ready,
                0,
                0,
                null,
                null,
                now,
                now,
                null);
    }

    private static class RecordingSchedulingUpdatePublisher
            implements SchedulingUpdatePublisher {

        private final List<TaskSchedulingUpdatedEvent> publishedEvents =
                new ArrayList<>();

        @Override
        public void publish(
                TaskSchedulingUpdatedEvent event) {

            publishedEvents.add(event);
        }

        public List<TaskSchedulingUpdatedEvent> getPublishedEvents() {
            return publishedEvents;
        }

        public void clear() {
            publishedEvents.clear();
        }
    }
}