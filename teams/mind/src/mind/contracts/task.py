"""Canonical Task contract mirrored from Inbox."""

from uuid import UUID

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    model_validator,
)

from .assignee import Assignee
from .task_enums import (
    ExtractionProvenance,
    RoleContext,
    TaskSourceType,
    TaskStatus,
    TaskTier,
)


class Task(BaseModel):
    """Canonical Task representation owned by Inbox."""

    model_config = ConfigDict(extra="forbid")

    # ------------------------------------------------------------------
    # Canonical identifiers
    # ------------------------------------------------------------------

    # Final canonical Task ID generated by Inbox.
    id: UUID

    # Internal Inbox organization identifier.
    organization_id: UUID

    project_id: UUID | None = None

    # ------------------------------------------------------------------
    # Task content
    # ------------------------------------------------------------------

    title: str = Field(min_length=1)
    description: str | None = None

    source_type: TaskSourceType
    source_ref: str | None = None

    # ------------------------------------------------------------------
    # Classification / MIND fields
    # ------------------------------------------------------------------

    tier: TaskTier | None = None
    role_context: RoleContext | None = None

    urgency: int | None = Field(
        default=None,
        ge=1,
        le=5,
    )

    effort_estimate_minutes: int | None = Field(
        default=None,
        gt=0,
    )

    effort_estimate_confidence: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
    )

    deadline: AwareDatetime | None = None

    # ------------------------------------------------------------------
    # Task state
    # ------------------------------------------------------------------

    # Owned by Inbox.
    status: TaskStatus

    # Calculated by Chain and materialized in Inbox.
    is_available: bool

    # Priority calculated by Chain.
    priority_score: float | None = None

    # Raw score produced by MIND.
    score: float | None = None

    snoozed_until: AwareDatetime | None = None

    # ------------------------------------------------------------------
    # Extraction metadata
    # ------------------------------------------------------------------

    extraction_provenance: ExtractionProvenance

    # General MIND confidence for ml_inferred Tasks.
    confidence: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
    )

    # ------------------------------------------------------------------
    # Owner / Assignees
    # ------------------------------------------------------------------

    # Final owner selected/confirmed by Inbox.
    # Owner is always a User.
    owner_id: UUID | None = None

    # Confidence originally provided by MIND for its owner suggestion.
    suggested_owner_confidence: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
    )

    # Final assignments stored by Inbox.
    # Can contain both Users and Teams.
    assignees: list[Assignee] = Field(
        default_factory=list
    )

    # ------------------------------------------------------------------
    # Inbox bookkeeping
    # ------------------------------------------------------------------

    created_by: UUID | None = None

    created_at: AwareDatetime
    updated_at: AwareDatetime

    completed_at: AwareDatetime | None = None

    # ------------------------------------------------------------------
    # Cross-field validation
    # ------------------------------------------------------------------

    @model_validator(mode="after")
    def validate_task_state(self) -> "Task":
        """Validate rules involving multiple Task fields."""

        if (
            self.extraction_provenance
            == ExtractionProvenance.ML_INFERRED
            and self.confidence is None
        ):
            raise ValueError(
                "confidence is required when "
                "extraction_provenance is ml_inferred"
            )

        if (
            self.status == TaskStatus.SNOOZED
            and self.snoozed_until is None
        ):
            raise ValueError(
                "snoozed_until is required when status is snoozed"
            )

        return self
    