"""Canonical Task contract mirrored from Inbox."""

from typing import Self
from uuid import UUID

from pydantic import (
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    JsonValue,
    model_validator,
)

from mind.contracts.assignee import Assignee
from mind.contracts.base_enums import SourceType
from mind.contracts.task_enums import (
    ExtractionProvenance,
    RoleContext,
    TaskStatus,
    TaskTier,
)


class Task(BaseModel):
    """Canonical Task representation owned by Inbox."""

    model_config = ConfigDict(extra="forbid")

    # ------------------------------------------------------------------
    # Canonical identifiers
    # ------------------------------------------------------------------

    task_id: UUID = Field(
        description="Final canonical Task ID generated by Inbox.",
    )

    organization_id: UUID = Field(
        description="Internal Inbox organization identifier.",
    )

    project_id: UUID | None = None

    # ------------------------------------------------------------------
    # Task content
    # ------------------------------------------------------------------

    title: str = Field(
        min_length=1,
    )

    description: str | None = None

    source_type: SourceType
    source_ref: str | None = None

    # ------------------------------------------------------------------
    # Classification / MIND fields
    # ------------------------------------------------------------------

    tier: TaskTier | None = None
    role_context: RoleContext | None = None

    urgency: int | None = Field(
        default=None,
        ge=1,
        le=5,
    )

    effort_estimate_minutes: int | None = Field(
        default=None,
        gt=0,
    )

    effort_estimate_confidence: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
    )

    deadline: AwareDatetime | None = None

    # ------------------------------------------------------------------
    # Task state
    # ------------------------------------------------------------------

    status: TaskStatus = Field(
        description="Task status owned by Inbox.",
    )

    is_available: bool = Field(
        description=(
            "Availability calculated by Chain "
            "and materialized in Inbox."
        ),
    )

    priority_score: float | None = Field(
        default=None,
        description="Priority calculated by Chain.",
    )

    snoozed_until: AwareDatetime | None = None

    # ------------------------------------------------------------------
    # Extraction metadata
    # ------------------------------------------------------------------

    extraction_provenance: ExtractionProvenance

    confidence: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description=(
            "General MIND confidence for ML_INFERRED Tasks."
        ),
    )

    # ------------------------------------------------------------------
    # Owner / Assignees
    # ------------------------------------------------------------------

    owner_id: UUID | None = Field(
        default=None,
        description=(
            "Final owner selected or confirmed by Inbox. "
            "Owner is always a User."
        ),
    )

    suggested_owner_user_id: UUID | None = Field(
        default=None,
        description="Owner originally suggested by MIND.",
    )

    suggested_owner_confidence: float | None = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description=(
            "Confidence originally provided by MIND "
            "for its owner suggestion."
        ),
    )

    assignees: list[Assignee] = Field(
        default_factory=list,
        description=(
            "Final assignments stored by Inbox. "
            "Can contain both Users and Teams."
        ),
    )

    # ------------------------------------------------------------------
    # Inbox bookkeeping
    # ------------------------------------------------------------------

    created_by: UUID | None = None

    created_at: AwareDatetime
    updated_at: AwareDatetime

    completed_at: AwareDatetime | None = None
    metadata: dict[str, JsonValue] | None = Field(
        default=None,
        description="Additional task metadata supplied by Inbox.",
    )

    # ------------------------------------------------------------------
    # Cross-field validation
    # ------------------------------------------------------------------

    @model_validator(mode="after")
    def validate_task_state(self) -> Self:
        """Validate rules involving multiple Task fields."""

        if (
            self.extraction_provenance
            == ExtractionProvenance.ML_INFERRED
            and self.confidence is None
        ):
            raise ValueError(
                "confidence is required when "
                "extraction_provenance is ML_INFERRED"
            )

        if (
            self.status == TaskStatus.SNOOZED
            and self.snoozed_until is None
        ):
            raise ValueError(
                "snoozed_until is required when status is SNOOZED"
            )

        return self
    